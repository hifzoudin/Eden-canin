export function slugify(value = "") {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-+/g, "-");
}

export function getBreedRoute(breed) {
  const input = typeof breed === "string" ? breed : breed?.slug || breed?.name || "";
  const slug = slugify(input).replace(/^puppies\//, "");
  return `/puppies/${slug || "chiots"}`;
}

export function getPuppyRoute(puppy) {
  const breed = puppy?.breed || puppy?.breedSlug || "";
  const breedSlug = slugify(breed);
  const puppySlug = slugify(puppy?.slug || puppy?.name || puppy?.id || "puppy");
  return `/puppies/${breedSlug}/${puppySlug}`;
}

export function getBreedPages() {
  return breedCatalog.map((breed) => ({
    ...breed,
    route: `/puppies/${breed.slug}`
  }));
}

export function getBreedMeta(breedSlug, lang = "fr") {
  const breed = breedCatalog.find((item) => item.slug === breedSlug) || breedCatalog[0];
  return {
    slug: breed.slug,
    label: breed.label[lang] || breed.label.fr,
    title: breed.title[lang] || breed.title.fr,
    description: breed.description[lang] || breed.description.fr,
    intro: breed.intro[lang] || breed.intro.fr,
    h1: `${breed.label[lang] || breed.label.fr} à vendre`,
    route: `/puppies/${breed.slug}`
  };
}

export function buildBreadcrumbs({ lang = "fr", breedSlug, puppyName, route }) {
  const items = [
    { label: lang === "fr" ? "Accueil" : lang === "en" ? "Home" : "Startseite", href: "/" },
    { label: lang === "fr" ? "Chiots" : lang === "en" ? "Puppies" : "Welpen", href: "/puppies" }
  ];

  if (breedSlug) {
    const breed = breedCatalog.find((item) => item.slug === breedSlug);
    if (breed) {
      items.push({ label: breed.label[lang] || breed.label.fr, href: `/puppies/${breed.slug}` });
    }
  }

  if (puppyName) {
    items.push({ label: puppyName, href: route || "/" });
  }

  return items;
}

